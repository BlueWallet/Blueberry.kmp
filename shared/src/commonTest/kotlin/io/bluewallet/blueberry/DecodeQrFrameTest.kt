private fun renderQrGrayscale(modules: List<String>, modulePx: Int): Triple<Int, Int, ByteArray> {
    val cols = modules.first().length
    val rows = modules.size
    val width = cols * modulePx
    val height = rows * modulePx
    val gray = ByteArray(width * height)
    for (y in 0 until height) {
        val row = modules[y / modulePx]
        for (x in 0 until width) {
            gray[y * width + x] = if (row[x / modulePx] == '1') 0 else 255.toByte()
        }
    }
    return Triple(width, height, gray)
}
