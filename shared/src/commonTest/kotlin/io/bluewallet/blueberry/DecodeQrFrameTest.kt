package io.bluewallet.blueberry

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull

class DecodeQrFrameTest {

    @Test
    fun reads_payload_from_grayscale_modules() {
        val (width, height, gray) = renderQrGrayscale(BC1Q_QR_MODULES, modulePx = 4)
        assertEquals(BC1Q_QR_PAYLOAD, decodeQrFrame(width, height, gray))
    }

    @Test
    fun blank_frame_is_null() {
        val size = 80
        assertNull(decodeQrFrame(size, size, ByteArray(size * size) { 255.toByte() }))
    }
}

